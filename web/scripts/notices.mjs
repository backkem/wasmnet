// The notices page: the licences of everything the page ships. This repository's own, the Rust
// crates compiled into the simulator and the device components, and the npm packages whose
// code runs in the tab (third-party.mjs collects the last two).

import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { licenceFiles, npmPackages, packageHtml, rustCrates } from './third-party.mjs';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(web, '..');

/**
 * The packages the page is built from: the simulator (wasm32-unknown-unknown) and the crates of
 * the devices it loads (`switch`, `node-http-server`, `node-http-get`: the netstack and two
 * apps), built for wasm32-wasip2.
 */
const ROOTS = ['wasmnet-web', 'wasmnet-switch', 'wasmnet-netstack', 'wasmnet-http-server', 'wasmnet-http-get'];
const TARGETS = ['wasm32-unknown-unknown', 'wasm32-wasip2'];

/** What the page ships: this repository's licence, its crates, its npm code. */
export function shipped() {
  return {
    own: licenceFiles(root),
    crates: rustCrates(root, ROOTS, TARGETS),
    // The kit's modules run in the tab, and the components' glue is generated by jco. None of
    // the three publishes a licence file in its npm package: their repositories' are in
    // licenses/.
    npm: npmPackages(web, ['codelib-web', '@bytecodealliance/jco', '@bytecodealliance/jco-transpile'], {
      'codelib-web': 'codelib-LICENSE',
      '@bytecodealliance/jco': 'jco-LICENSE',
      '@bytecodealliance/jco-transpile': 'jco-LICENSE',
    }),
  };
}

const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const link = (url) => `<a href="${esc(url)}">${esc(url)}</a>`;

/** The notices page for what [`shipped`] found. */
export function noticesHtml(rest) {
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="light dark">
  <title>Third-party notices</title>
  <link rel="stylesheet" href="style.css">
</head>
<body class="notices">
<header>
  <h1>Third-party notices</h1>
  <p><a href="./">Back to the page</a></p>
</header>
<main>
<h2>The simulator and the devices</h2>
<p>
  The simulator (<code>wasmnet_web.wasm</code>) and the devices (<code>components/</code>,
  <code>cores/</code>) are compiled from ${link('https://github.com/backkem/wasmnet')}, under the
  MIT licence or the Apache License 2.0, at your option:
</p>
${rest.own.map((f) => `<details>\n<summary>${esc(f.file)}</summary>\n<pre>${esc(f.text)}</pre>\n</details>`).join('\n')}
<p>
  They are linked with the Rust standard library (MIT or Apache-2.0, the same two texts;
  ${link('https://github.com/rust-lang/rust/blob/master/COPYRIGHT')}) and with these
  ${rest.crates.length} crates, each under its own licence:
</p>
${rest.crates.map(packageHtml).join('\n')}
<h2>The code that runs them in the tab</h2>
<p>
  The page runs the devices on codelib-web, a browser host for WebAssembly components, and the
  JavaScript around their modules is generated by jco.
</p>
${rest.npm.map(packageHtml).join('\n')}
</main>
</body>
</html>
`;
}
